-- app_db V007: группы статусов потребностей по умолчанию (KON-61, FR-035).
-- Статусы - workflow Jira «Аналитик», имена как в Jira. «Интервью не пройдено» входит в две группы намеренно.
-- Группа «Прочие» виртуальная (вычисляется в API), в таблицы не кладётся. Состав потом меняет администратор.
-- Идемпотентно: уже существующая группа (по имени) и её состав не перезаписываются.
INSERT INTO app.status_group (name, sort_order) VALUES
    ('Без кандидата', 1), ('Кандидат назначен', 2), ('Интервью', 3), ('Закреплён', 4)
ON CONFLICT (name) DO NOTHING;

INSERT INTO app.status_group_status (group_id, status_name)
SELECT g.id, v.status_name
FROM (VALUES
    ('Без кандидата', 'Требуется кандидат'),
    ('Без кандидата', 'Поиск кандидата'),
    ('Без кандидата', 'Найм'),
    ('Без кандидата', 'Отказ по кандидату'),
    ('Без кандидата', 'Интервью не пройдено'),
    ('Кандидат назначен', 'Кандидат назначен'),
    ('Интервью', 'Подготовка к интервью'),
    ('Интервью', 'Интервью состоялось'),
    ('Интервью', 'Интервью пройдено'),
    ('Интервью', 'Интервью не пройдено'),
    ('Закреплён', 'Закреплен за проектом')
) AS v (group_name, status_name)
JOIN app.status_group g ON g.name = v.group_name
ON CONFLICT (group_id, status_name) DO NOTHING;

